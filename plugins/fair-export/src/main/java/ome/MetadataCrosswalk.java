package org.youscope.plugin.fairexport.ome;

import java.util.Collections;
import java.util.HashMap;
import java.util.Map;

/**
 * Maps the names of YouScope metadata properties to their representation in the
 * OME data model.
 * <p>
 * The OME data model has native elements for hardware and acquisition metadata,
 * but almost none for
 * biological metadata: there is no OME element for species, strain, genotype or
 * treatment. The
 * community solution, and the one OMERO and the BioImage Archive expect, is to
 * store such fields as
 * map annotations. This class therefore distinguishes two kinds of targets:
 * </p>
 * <ul>
 * <li>{@link Slot#ANNOTATION}: the property becomes a key/value pair of a map
 * annotation. This is the
 * default and applies to everything not listed in the table below.</li>
 * <li>Any other {@link Slot}: the property is written into a native OME
 * element and is <i>not</i>
 * additionally annotated, to avoid duplicate information in the file.</li>
 * </ul>
 * <p>
 * Annotated properties are grouped into one map annotation per category, and
 * the category determines
 * the annotation namespace. Since the category is derived from the sub-folder
 * of
 * {@code configuration/metadata} a definition lives in, adding a new metadata
 * definition XML file
 * automatically produces correctly namespaced OME output without any code
 * change here. Only fields
 * which have a native OME slot need an entry in the table.
 * </p>
 * 
 * @author Andreas P. Cuny
 */
public class MetadataCrosswalk {
	/**
	 * Base of the namespaces used for map annotations generated by YouScope. The
	 * category is appended,
	 * e.g. {@code https://youscope.org/schemas/fair/1.0/biological}.
	 */
	public static final String NAMESPACE_BASE = "https://youscope.org/schemas/fair/1.0/";
	/**
	 * Namespace used for properties without category.
	 */
	public static final String NAMESPACE_GENERAL = NAMESPACE_BASE + "general";
	/**
	 * Namespace of the annotation carrying the acquisition software and the
	 * YouScope configuration
	 * provenance. Always written, independent of user metadata.
	 */
	public static final String NAMESPACE_PROVENANCE = NAMESPACE_BASE + "provenance";

	/**
	 * The place in the OME data model a metadata property is written to.
	 */
	public enum Slot {
		/** Key/value pair of a map annotation attached to the image. The default. */
		ANNOTATION,
		/** {@code Image/Description}. */
		IMAGE_DESCRIPTION,
		/** {@code Experiment/Description}. */
		EXPERIMENT_DESCRIPTION,
		/** {@code Experimenter/UserName}. */
		EXPERIMENTER_NAME,
		/** {@code Experimenter/Email}. */
		EXPERIMENTER_EMAIL,
		/** {@code Experimenter/Institution}. */
		EXPERIMENTER_INSTITUTION,
		/** {@code ImagingEnvironment/Temperature}. */
		ENVIRONMENT_TEMPERATURE,
		/** {@code ImagingEnvironment/CO2Percent}. */
		ENVIRONMENT_CO2,
		/** {@code ImagingEnvironment/Humidity}. */
		ENVIRONMENT_HUMIDITY,
		/** {@code ImagingEnvironment/AirPressure}. */
		ENVIRONMENT_AIR_PRESSURE,
		/** {@code Objective/Immersion}. */
		OBJECTIVE_IMMERSION,
		/** {@code Objective/Correction}. */
		OBJECTIVE_CORRECTION,
		/**
		 * {@code Channel/Fluor}. Applied to every channel which does not define its own
		 * fluorophore.
		 */
		CHANNEL_FLUOR,
		/** {@code Channel/AcquisitionMode}. */
		CHANNEL_ACQUISITION_MODE,
		/** {@code Channel/ContrastMethod}. */
		CHANNEL_CONTRAST_METHOD,
		/** {@code Plate/Name}. */
		PLATE_NAME,
		/** {@code Well}, parsed as a well position such as "B7". */
		WELL_POSITION
	}

	/**
	 * One entry of the crosswalk.
	 */
	public static class Mapping {
		/** Target slot in the OME data model. */
		public final Slot slot;
		/** Key used in the map annotation. Defaults to the property name. */
		public final String annotationKey;
		/**
		 * Ontology or controlled vocabulary the values of this property should come
		 * from, for
		 * documentation and for the RO-Crate export. May be null.
		 */
		public final String vocabulary;

		Mapping(Slot slot, String annotationKey, String vocabulary) {
			this.slot = slot;
			this.annotationKey = annotationKey;
			this.vocabulary = vocabulary;
		}
	}

	private static final Map<String, Mapping> DEFAULT_MAPPINGS = createDefaultMappings();

	private final Map<String, Mapping> mappings = new HashMap<String, Mapping>(DEFAULT_MAPPINGS);

	/**
	 * Creates a crosswalk with the default mappings.
	 */
	public MetadataCrosswalk() {
		// nothing to do.
	}

	private static Map<String, Mapping> createDefaultMappings() {
		HashMap<String, Mapping> result = new HashMap<String, Mapping>();

		// Provenance
		put(result, "Operator", Slot.EXPERIMENTER_NAME, null);
		put(result, "User", Slot.EXPERIMENTER_NAME, null);
		put(result, "Email", Slot.EXPERIMENTER_EMAIL, null);
		put(result, "Institution", Slot.EXPERIMENTER_INSTITUTION, "ROR");
		// ORCID, Laboratory, Grant, DOIs and License have no native OME element. They
		// stay annotations
		// here and become first class citizens in the RO-Crate export.
		put(result, "ORCID", Slot.ANNOTATION, "ORCID");
		put(result, "License", Slot.ANNOTATION, "SPDX");

		// Eexperimental
		put(result, "Comments", Slot.IMAGE_DESCRIPTION, null);
		put(result, "Experiment ID", Slot.EXPERIMENT_DESCRIPTION, null);

		// Imaging environment
		put(result, "Temperature", Slot.ENVIRONMENT_TEMPERATURE, null);
		put(result, "CO2", Slot.ENVIRONMENT_CO2, null);
		put(result, "Humidity", Slot.ENVIRONMENT_HUMIDITY, null);
		put(result, "Air pressure", Slot.ENVIRONMENT_AIR_PRESSURE, null);

		// Optics
		put(result, "Immersion", Slot.OBJECTIVE_IMMERSION, null);
		put(result, "Immersion medium", Slot.OBJECTIVE_IMMERSION, null);
		put(result, "Correction", Slot.OBJECTIVE_CORRECTION, null);

		// Labelling and modality
		put(result, "Fluorophore", Slot.CHANNEL_FLUOR, null);
		put(result, "Modality", Slot.CHANNEL_ACQUISITION_MODE, null);
		put(result, "Image modality", Slot.CHANNEL_ACQUISITION_MODE, null);
		put(result, "Contrast method", Slot.CHANNEL_CONTRAST_METHOD, null);

		// Screening
		put(result, "Plate ID", Slot.PLATE_NAME, null);
		put(result, "Well", Slot.WELL_POSITION, null);

		// Annotated, but with a recommended vocabulary
		put(result, "Species", Slot.ANNOTATION, "NCBITaxon");
		put(result, "Sex", Slot.ANNOTATION, "PATO");
		put(result, "Tissue", Slot.ANNOTATION, "UBERON");
		put(result, "Organ", Slot.ANNOTATION, "UBERON");
		put(result, "Cell line", Slot.ANNOTATION, "Cellosaurus");
		put(result, "Developmental stage", Slot.ANNOTATION, "EFO");
		put(result, "Compound", Slot.ANNOTATION, "ChEBI");

		return Collections.unmodifiableMap(result);
	}

	private static void put(Map<String, Mapping> target, String propertyName, Slot slot, String vocabulary) {
		target.put(normalize(propertyName), new Mapping(slot, propertyName, vocabulary));
	}

	private static String normalize(String propertyName) {
		return propertyName == null ? "" : propertyName.trim().toLowerCase();
	}

	/**
	 * Overrides or adds a mapping, e.g. from a facility specific configuration.
	 * 
	 * @param propertyName Name of the metadata property.
	 * @param slot         Target slot in the OME data model.
	 * @param vocabulary   Recommended vocabulary, or null.
	 */
	public void setMapping(String propertyName, Slot slot, String vocabulary) {
		if (propertyName == null || propertyName.isEmpty() || slot == null)
			return;
		mappings.put(normalize(propertyName), new Mapping(slot, propertyName, vocabulary));
	}

	/**
	 * Returns the mapping of a metadata property. Properties which are not part of
	 * the crosswalk are
	 * mapped to {@link Slot#ANNOTATION} using their own name as the annotation key,
	 * so that no user
	 * entered metadata is ever silently dropped.
	 * 
	 * @param propertyName Name of the metadata property.
	 * @return Mapping of the property. Never null.
	 */
	public Mapping getMapping(String propertyName) {
		Mapping mapping = mappings.get(normalize(propertyName));
		if (mapping != null)
			return mapping;
		return new Mapping(Slot.ANNOTATION, propertyName, null);
	}

	/**
	 * Returns the map annotation namespace for a metadata category.
	 * 
	 * @param category Category of the metadata definition, i.e. its sub-folder
	 *                 below
	 *                 {@code configuration/metadata}. May be null or empty.
	 * @return Namespace to be used for the map annotation.
	 */
	public String getNamespace(String category) {
		if (category == null || category.trim().isEmpty())
			return NAMESPACE_GENERAL;
		return NAMESPACE_BASE + category.trim().toLowerCase().replace(' ', '-');
	}
}
